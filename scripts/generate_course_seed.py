"""Generate db/repeatable/course_units.sql from curriculum/russian/a1-course.json.

The seed carries the SHA-256 of the exact course file, so the database always
records which course version it was loaded from. Run with --check to fail when
the committed seed is out of date (used by the tests and CI).
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COURSE = ROOT / "curriculum" / "russian" / "a1-course.json"
OUT = ROOT / "db" / "repeatable" / "course_units.sql"


def sql_text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def build() -> str:
    raw = COURSE.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    data = json.loads(raw)
    content = data.get("unitContent", {})
    rows = []
    for unit in sorted(data["units"], key=lambda u: u["order"]):
        detail = content.get(unit["id"], {})
        title = detail.get("title") or unit["title"]
        objective = detail.get("objective") or unit.get("objective") or title
        vocab = len(detail.get("vocabulary", [])) or 100
        minutes = detail.get("estimatedMinutes") or 15
        # The course JSON uses "current" for the learner-facing unit; the database only
        # distinguishes planned / active / retired.
        status = unit.get("status") if unit.get("status") in ("planned", "retired") else "active"
        rows.append(
            f"    ({sql_text(unit['id'])}, {int(unit['order'])}, {sql_text(title)}, "
            f"{sql_text(objective)}, {sql_text(status)}, {int(vocab)}, {int(minutes)})"
        )
    values = ",\n".join(rows)
    return f"""-- GENERATED by scripts/generate_course_seed.py. Do not edit by hand.
-- Source: curriculum/russian/a1-course.json (sha256 {digest})

BEGIN;

INSERT INTO course_versions (schema_version, content_hash, source_name)
VALUES ('1.0', '{digest}', 'curriculum/russian/a1-course.json')
ON CONFLICT (schema_version, content_hash) DO NOTHING;

INSERT INTO course_units
    (id, course_version_id, unit_order, title, objective, status, vocabulary_count, estimated_minutes)
SELECT v.id, cv.id, v.unit_order, v.title, v.objective, v.status, v.vocabulary_count, v.estimated_minutes
FROM course_versions cv
CROSS JOIN (VALUES
{values}
) AS v(id, unit_order, title, objective, status, vocabulary_count, estimated_minutes)
WHERE cv.schema_version = '1.0'
  AND cv.content_hash = '{digest}'
ON CONFLICT (id) DO UPDATE SET
    course_version_id = EXCLUDED.course_version_id,
    unit_order = EXCLUDED.unit_order,
    title = EXCLUDED.title,
    objective = EXCLUDED.objective,
    status = EXCLUDED.status,
    vocabulary_count = EXCLUDED.vocabulary_count,
    estimated_minutes = EXCLUDED.estimated_minutes,
    updated_at = now();

COMMIT;
"""


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("db/repeatable/course_units.sql is out of date; run scripts/generate_course_seed.py", file=sys.stderr)
            return 1
        print("course seed is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
